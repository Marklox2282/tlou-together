#pragma once
// Общие враги: урон и смерти врагов у одного игрока повторяются у другого. У каждого свой ИИ,
// но враг с тем же именем (sid спавнера) получает тот же урон и умирает от выстрела партнёра.

#include <cstdint>
#include <vector>

namespace enemies {

struct Change {
	uint64_t npc;
	float health;  // здоровье после удара (0 при смерти)
	bool dead;
};

// Скриптовый контекст, раз за кадр: следит за врагами (10 раз в секунду) и применяет
// изменения от партнёра. puppet - своя марионетка, её не трогаем.
void Tick(uint64_t puppet);

// Позиции врагов. Хозяин (sendPositions) шлёт ближайших; у гостя враг, ушедший дальше 6 м от
// позиции у хозяина, переносится туда (не чаще раза в 3 с). ИИ у гостя остаётся: враги на него
// нападают как обычно.
struct Position { uint64_t npc; float pos[3], rot[4]; };
void SetSendPositions(bool on);
// Полная синхронизация (ini enemy_sync=full, пока опыт): у гостя ИИ врагов выключен, они идут за
// врагами хозяина своей анимацией. Атаки врагов ещё не копируются - гостя они не трогают.
void SetFullSync(bool on);
// Идёт катсцена (своя или партнёра): позиции врагов и спутников не трогаем (переносило Тесс в кадр).
void SetCutscene(bool on);
std::vector<Position> TakePositions();     // хозяин: для отправки
void ReceivePosition(const Position& p);   // гость: от хозяина

// Любой поток (сеть - в игровом кадре):
std::vector<Change> TakeOutgoing();  // свои удары и убийства для отправки
void Receive(const Change& c);       // от партнёра
void ResendDead();                   // переслать уже убитых на главе врагов опоздавшему напарнику
void OnReload();                     // перезагрузка чекпоинта / смерть: очистить кэш попытки
void Reset();                        // новое подключение: забыть, что знали
// Выстрелы: копии партнёра (её пули - только для вида: урон партнёр присылает сам) и свои.
// Удар по врагу в 0.4 с после выстрела копии, когда сам игрок не стрелял, откатывается.
void NoteCopyShot();
void NoteOwnShot();

}  // namespace enemies
